import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { startServer } from './helpers.js';

const server = await startServer();
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(20000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const pass = message => console.log(`PASS ${message}`);
const shelf = () => page.locator('.book-shelf');
const card = id => page.locator(`[data-book-row="${id}"]`);
const menu = id => page.locator(`[data-book-menu="${id}"]`);
const info = id => page.locator(`[data-edit-book="${id}"]`);
const world = id => page.locator(`[data-open-book="${id}"]`);
const apply = () => page.locator('#book-form button[type="submit"]').click();
const save = async publish => {
  await page.locator(publish ? '#publish' : '#save').click();
  await expect(page.locator('#save-state')).toHaveText(publish ? '공개 완료' : '변경사항 저장됨');
};
await mkdir('test-results/book-management', { recursive: true });
try {
  await page.goto(server.url + '/admin/');
  await expect(shelf()).toBeVisible();
  await expect(menu('alice')).toBeVisible();
  await expect(info('alice')).toBeHidden();
  await expect(world('alice')).toBeHidden();
  await card('alice').locator('.book-cover').click();
  await expect(page.locator('#studio-world, #book-form')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/book-management/desktop.png', fullPage: true });
  await page.locator('#book-search').fill('오즈');
  await page.locator('#book-filter').selectOption('public');
  await expect(card('alice')).toBeHidden();
  await menu('oz').focus();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  await expect(page.getByLabel('책 제목', { exact: true })).toHaveValue('오즈의 마법사');
  await expect(page).toHaveURL(/status=public&modal=book&id=oz$/);
  await expect(page.locator('#studio-world')).toHaveCount(0);
  await page.goBack();
  await expect(page.locator('#book-form')).toHaveCount(0);
  await expect(page.locator('#book-search')).toHaveValue('오즈');
  await page.goForward();
  await expect(page.getByLabel('책 제목', { exact: true })).toHaveValue('오즈의 마법사');
  await page.reload();
  await expect(page.getByLabel('책 제목', { exact: true })).toHaveValue('오즈의 마법사');
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await expect(page).not.toHaveURL(/modal=/);
  pass('Row menus offer three actions; metadata opens the right book without 3D, including keyboard, reload and history');

  await menu('oz').click();
  await info('oz').click();
  await page.getByLabel('책 제목', { exact: true }).fill('오즈의 마법사 정보 수정');
  await page.getByLabel('분류', { exact: true }).fill('고전');
  const png = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 400; canvas.height = 570;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#9f664e'; ctx.fillRect(0, 0, 400, 570);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  await page.locator('#book-cover-file').setInputFiles({ name: 'cover.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await expect(page.locator('#book-cover-status')).toHaveText('업로드 완료');
  await apply();
  await expect(page.locator('#book-form, #studio-world')).toHaveCount(0);
  await expect(card('oz')).toContainText('오즈의 마법사 정보 수정');
  await expect(menu('oz')).toBeFocused();
  await expect(page.locator('#book-search')).toHaveValue('오즈');
  await save(false);
  await page.reload();
  await menu('oz').click();
  await info('oz').click();
  await expect(page.getByLabel('분류', { exact: true })).toHaveValue('고전');
  await expect(page.locator('#book-cover-preview')).toBeVisible();
  await page.getByLabel('책 제목', { exact: true }).fill('취소할 수정');
  await page.keyboard.press('Escape');
  await expect(card('oz')).toContainText('오즈의 마법사 정보 수정');
  await save(true);
  const published = await (await page.request.get(server.url + '/api/library')).json();
  const oz = published.books.find(b => b.id === 'oz');
  expect(oz).toMatchObject({ title: '오즈의 마법사 정보 수정', category: '고전' });
  expect(oz.cover).toMatch(/^\/uploads\/.+\.png$/);
  pass('Cover and genre edits apply, save and publish from the shelf; cancel leaves stored metadata unchanged');

  await menu('oz').click();
  await world('oz').click();
  await expect(page.locator('#studio-world canvas')).toBeVisible();
  await expect(page.locator('[data-chapter-edit="oz-1"]')).toBeVisible();
  const count = await page.locator('[data-chapter-row]').count();
  await page.locator('#add-chapter').click();
  await page.getByLabel('챕터 제목', { exact: true }).fill('관리 확인 챕터');
  await page.locator('#chapter-form .primary-button').click();
  await expect(page.locator('[data-chapter-row]')).toHaveCount(count + 1);
  await page.locator('[data-chapter-edit]').last().click();
  await page.getByLabel('챕터 제목', { exact: true }).fill('수정한 챕터');
  await page.locator('#chapter-form .primary-button').click();
  await expect(page.locator('[data-chapter-row]').last()).toContainText('수정한 챕터');
  await page.locator('[data-chapter-edit]').last().click();
  await page.locator('#delete-chapter').click();
  await page.locator('#confirm-action').click();
  await expect(page.locator('[data-chapter-row]')).toHaveCount(count);
  await save(false);
  await page.locator('#back-library').click();
  await expect(page.locator('#book-search')).toHaveValue('오즈');
  pass('World editing retains chapter add, edit and delete, then returns to the filtered shelf');

  await page.locator('#new-book').click();
  await page.getByLabel('책 제목', { exact: true }).fill('새 도서 관리 확인');
  await apply();
  await expect(page.locator('#book-form, #studio-world')).toHaveCount(0);
  await expect(page.locator('#book-search')).toHaveValue('');
  await expect(page.locator('#book-filter')).toHaveValue('all');
  await expect(page).toHaveURL(server.url + '/admin/');
  const created = page.getByRole('article', { name: '새 도서 관리 확인', exact: true });
  await expect(created).toBeVisible();
  await expect(created.locator('[data-book-menu]')).toBeFocused();
  await save(false);
  await created.locator('[data-book-menu]').click();
  await created.locator('[data-open-book]').click();
  await expect(page.locator('#studio-world canvas')).toBeVisible();
  await page.locator('#back-library').click();
  // Delete a book other than the one most recently opened in 3D.
  await menu('oz').click();
  await info('oz').click();
  await page.locator('#delete-book').click();
  await page.locator('#confirm-action').click();
  await expect(card('oz')).toHaveCount(0);
  await expect(created).toBeVisible();
  await expect(card('alice')).toBeVisible();
  await save(false);
  await page.reload();
  await expect(card('oz')).toHaveCount(0);
  pass('New books stay on the shelf and clear filters; deleting metadata targets the chosen book');

  await page.locator('[data-book-drag="alice"]').focus();
  await page.keyboard.press('Alt+ArrowRight');
  await expect(page.locator('[data-book-row]').last()).toHaveAttribute('data-book-row', 'alice');
  await save(false);
  for (const width of [320, 375, 768]) {
    await page.setViewportSize({ width, height: 900 });
    await expect(menu('alice')).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await menu('alice').click();
    await expect(page.getByRole('menuitem')).toHaveCount(3);
    await expect(info('alice')).toBeVisible();
    await expect(world('alice')).toBeVisible();
    const box = await page.getByRole('menu').boundingBox();
    expect(box.x).toBeGreaterThanOrEqual(0);
    expect(box.x + box.width).toBeLessThanOrEqual(width);
    expect(box.y + box.height).toBeLessThanOrEqual(900);
    await info('alice').click();
    await expect(page.locator('#book-form')).toBeVisible();
    await page.getByRole('button', { name: '닫기', exact: true }).click();
    await expect(page).not.toHaveURL(/modal=/);
    if (width === 375) await page.screenshot({ path: 'test-results/book-management/mobile.png', fullPage: true });
  }
  await page.goto(server.url + '/admin/?modal=book&id=missing');
  await expect(shelf()).toBeVisible();
  await expect(page.locator('#book-form')).toHaveCount(0);
  await expect(page).toHaveURL(server.url + '/admin/');
  expect(errors).toEqual([]);
  pass('Order, mobile actions and missing-book addresses work without runtime errors');
} finally {
  await browser.close();
  await server.stop();
}
