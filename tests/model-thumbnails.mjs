import { chromium, expect } from '@playwright/test';
import { startServer, sampleGLB } from './helpers.js';

const server=await startServer(4297);
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try {
  await page.goto(server.url+'/admin/');
  await page.getByRole('button',{name:'3D 모델 보관함',exact:true}).click();
  await expect(page.locator('.model-thumbnail img')).toHaveCount(9);
  expect(await page.locator('.model-thumbnail img').evaluateAll(images=>images.every(image=>image.complete&&image.naturalWidth===640))).toBe(true);
  await page.screenshot({path:'docs/screenshots/model-thumbnails.png',fullPage:true});
  await page.locator('[data-preview-model]').first().click();
  const preview=page.locator('#single-preview canvas');
  await expect(preview).toBeVisible();
  await expect(preview).toHaveAttribute('aria-label',/선택한 모델 미리보기/);
  await page.screenshot({path:'docs/screenshots/model-only-preview.png'});
  const box=await preview.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width/2+100,box.y+box.height/2+40,{steps:10});
  await page.mouse.up();
  await page.mouse.wheel(0,-150);
  await page.keyboard.press('Escape');
  await expect(preview).toHaveCount(0);
  await page.locator('#new-model').click();
  await page.getByLabel('모델 이름',{exact:true}).fill('썸네일 검증 모델');
  await page.getByLabel('제작자 및 사용 권한').fill('자체 제작 테스트');
  await page.locator('[name="file"]').setInputFiles({name:'model.glb',mimeType:'model/gltf-binary',buffer:sampleGLB()});
  await expect(page.locator('#upload-status')).toContainText('업로드 완료');
  await page.locator('#model-submit').click();
  await expect(page.locator('#toast')).toContainText('썸네일');
  await expect(page.locator('#model-form')).toBeVisible();
  await page.locator('[name="thumbnail"]').setInputFiles({name:'bad.png',mimeType:'image/png',buffer:Buffer.from('invalid')});
  await expect(page.locator('#model-submit')).toBeEnabled();
  await expect(page.locator('#thumbnail-preview')).toBeHidden();
  const png=Buffer.from(await page.evaluate(()=>{const c=document.createElement('canvas');c.width=320;c.height=180;const ctx=c.getContext('2d');ctx.fillStyle='#659373';ctx.fillRect(40,20,240,140);return c.toDataURL().split(',')[1];}),'base64');
  await page.locator('[name="thumbnail"]').setInputFiles({name:'thumb.png',mimeType:'image/png',buffer:png});
  await expect(page.locator('#thumbnail-status')).toContainText('업로드 완료');
  await expect(page.locator('#thumbnail-preview')).toBeVisible();
  await page.locator('#model-submit').click();
  const card=page.locator('.model-card').filter({hasText:'썸네일 검증 모델'});
  await expect(card.locator('.model-thumbnail img')).toHaveAttribute('src',/\/uploads\/.*\.png/);
  await page.locator('#save').click();
  await expect(page.locator('#save-state')).toHaveText('변경사항 저장됨');
  const state=await (await page.request.get(server.url+'/api/studio')).json();
  const model=state.library.models.find(model=>model.name==='썸네일 검증 모델');
  expect(model.thumbnail).toMatch(/\.png$/);
  delete model.thumbnail;
  const rejected=await page.request.put(server.url+'/api/studio',{headers:{'X-On-The-Book':'studio'},data:state});
  expect(rejected.status()).toBe(400);
  expect((await rejected.json()).error).toContain('썸네일');
  model.id='new-without-thumbnail';
  expect((await page.request.put(server.url+'/api/studio',{headers:{'X-On-The-Book':'studio'},data:state})).status()).toBe(400);
  await page.reload();
  await page.getByRole('button',{name:'3D 모델 보관함',exact:true}).click();
  await expect(card.locator('.model-thumbnail img')).toHaveAttribute('src',/\/uploads\/.*\.png/);
  await card.locator('[data-edit-model]').click();
  await expect(page.locator('#thumbnail-preview')).toBeVisible();
  await page.locator('#model-submit').click();
  await expect(page.locator('#model-form')).toHaveCount(0);
  expect(errors).toEqual([]);
  console.log('PASS: real thumbnails, required upload, invalid image, persistence, edit and server validation');
} finally { await browser.close(); await server.stop(); }
