import { chromium, expect } from '@playwright/test';
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { startServer } from './helpers.js';

await mkdir('output/image-placeholders', { recursive: true });
const server = await startServer();
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
const request = async (url, method = 'GET', body) => (await fetch(server.url + url, { method, headers: { 'X-On-The-Book': 'studio', 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined })).json();
const report = [];
try {
  const uploads = [];
  for (const color of ['#125cbb', '#ef3440', '#14966c']) {
    const svg = `<svg width="240" height="160" xmlns="http://www.w3.org/2000/svg"><rect width="240" height="160" fill="${color}"/><circle cx="170" cy="50" r="35" fill="#ffdc8f"/><path d="M0 160 L85 65 L190 160" fill="#234532"/></svg>`;
    const buffer = await sharp(Buffer.from(svg)).png().toBuffer();
    const form = new FormData(); form.append('image', new Blob([buffer], { type: 'image/png' }), 'scene.png');
    uploads.push(await (await fetch(server.url + '/api/floor/upload', { method: 'POST', headers: { 'X-On-The-Book': 'studio' }, body: form })).json());
  }
  const state = await request('/api/studio');
  state.library.books.forEach((book, i) => { book.cover = uploads[i].url; book.thumbnail = uploads[i].url; book.chapters.forEach((chapter, j) => chapter.thumbnail = uploads[(i + j) % 2].url); });
  state.library.books[1].chapters[1].thumbnail = '';
  await request('/api/studio', 'PUT', { ...state, publish: true });
  const studio = await request('/api/studio');
  const live = await request('/api/library');
  // Include an unused replacement in the browser registry solely for a race-condition test.
  live.imagePreviews[uploads[2].url] = uploads[2].preview;
  await page.route('**/api/library', route => route.fulfill({ json: live }));
  let release;
  let gate = new Promise(resolve => release = resolve);
  await page.route('**/uploads/*.png', async route => { await gate; await route.continue(); });
  await page.goto(server.url + '/client/', { waitUntil: 'domcontentloaded' });
  const image = page.locator('.catalog-cover img').first();
  await expect(image).toHaveClass(/image-preview-pending/);
  const layer = image.locator('xpath=preceding-sibling::*[contains(@class,"image-preview-layer")]');
  await expect(layer).toBeVisible();
  expect(await layer.evaluate(el => getComputedStyle(el).backgroundImage)).toContain('data:image/webp;base64,');
  const before = await image.boundingBox();
  await page.waitForTimeout(1000); // Let the existing page entrance finish while originals remain gated.
  await page.screenshot({ path: 'output/image-placeholders/client-slow.png', fullPage: true });
  release(); gate = Promise.resolve();
  await expect(image).not.toHaveClass(/image-preview-pending/);
  await expect(layer).toHaveCount(0);
  const after = await image.boundingBox();
  expect(after.width).toBeCloseTo(before.width, 1); expect(after.height).toBeCloseTo(before.height, 1);
  report.push('slow loading: inline preview and stable frame');
  await page.screenshot({ path: 'output/image-placeholders/client-loaded.png', fullPage: true });
  const scene = page.locator('[data-scene-tab]').last(); await scene.click();
  await expect(page.locator('.scene-cover img')).toHaveAttribute('src', uploads[1].url);
  await expect(page.locator('.scene-image .image-preview-empty-note').first()).toHaveText('이미지 준비 중');
  report.push('book and scene switching');
  gate = new Promise(resolve => release = resolve);
  await image.evaluate((el, url) => el.src = url, uploads[2].url);
  await expect(image).toHaveClass(/image-preview-pending/);
  await expect(layer).toBeVisible();
  expect(await layer.evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(20, 150, 108)');
  // Switch back before the first decode finishes: an older callback cannot reveal the replaced picture.
  await image.evaluate((el, url) => el.src = url, uploads[0].url);
  release(); gate = Promise.resolve();
  await expect(image).not.toHaveClass(/image-preview-pending/);
  await expect(layer).toHaveCount(0);
  report.push('rapid replacement ignores stale decoding');
  // Force genuinely new requests to exercise both fallback states.
  const colorOnly = '/uploads/00000000-0000-4000-8000-000000000002.png';
  const missing = '/uploads/00000000-0000-4000-8000-000000000003.png';
  const replacement = async route => { await gate; await route.fulfill({ body: await sharp({ create: { width: 60, height: 60, channels: 3, background: '#3b8871' } }).png().toBuffer(), contentType: 'image/png' }); };
  await page.route('**' + colorOnly, replacement);
  await page.route('**' + missing, replacement);
  // Static data on an image is also used by the build-generated about page.
  gate = new Promise(resolve => release = resolve);
  await image.evaluate((el, url) => { el.dataset.imagePreview = JSON.stringify({ color: '#3b8871', width: 60, height: 60 }); el.src = url; }, colorOnly);
  await expect(layer).toBeVisible();
  expect(await layer.evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(59, 136, 113)');
  expect(await layer.evaluate(el => getComputedStyle(el).backgroundImage)).toBe('none');
  await image.evaluate((el, url) => { delete el.dataset.imagePreview; el.src = url; }, missing);
  await expect(layer).toHaveText('이미지를 불러오는 중');
  release(); gate = Promise.resolve();
  await expect(layer).toHaveCount(0);
  await image.evaluate((el, url) => el.src = url, uploads[0].url);
  await expect(image).not.toHaveClass(/image-preview-pending/);
  await expect(layer).toHaveCount(0);
  report.push('colour-only and missing metadata fallbacks, cached originals');
  const bad = '/uploads/00000000-0000-4000-8000-000000000001.png';
  await image.evaluate((el, url) => el.src = url, bad);
  await expect(layer).toHaveText('이미지를 불러오지 못했어요');
  expect(await layer.evaluate(el => getComputedStyle(el).backgroundImage)).toBe('none');
  report.push('failure removes blur and shows a message');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(server.url + '/client/');
  await page.screenshot({ path: 'output/image-placeholders/client-mobile.png', fullPage: true });
  report.push('mobile reader');
  await page.setViewportSize({ width: 1440, height: 1000 });
  gate = new Promise(resolve => release = resolve);
  await page.goto(server.url + '/admin/', { waitUntil: 'domcontentloaded' });
  const adminImage = page.locator('.book-cover img').first();
  await expect(adminImage).toHaveClass(/image-preview-pending/);
  await page.screenshot({ path: 'output/image-placeholders/admin-slow.png', fullPage: true });
  release(); gate = Promise.resolve();
  await expect(adminImage).not.toHaveClass(/image-preview-pending/);
  await page.locator('[data-open-book]').first().click();
  await page.locator('#edit-book').click();
  await expect(page.locator('#book-cover-preview')).toBeVisible();
  await expect(page.locator('.crop-box img').first()).toBeVisible();
  await page.locator('#book-cover-clear').click();
  await expect(page.locator('#book-cover-preview')).toBeHidden();
  await page.locator('#book-cover-file').setInputFiles({ name: 'new.png', mimeType: 'image/png', buffer: await sharp({ create: { width: 60, height: 60, channels: 4, background: { r: 100, g: 160, b: 100, alpha: 0.4 } } }).png().toBuffer() });
  await expect(page.locator('#book-cover-status')).toHaveText('업로드 완료');
  await expect(page.locator('#book-cover-preview')).not.toHaveClass(/image-preview-pending/);
  expect(await page.locator('#book-cover-preview').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0)');
  await page.screenshot({ path: 'output/image-placeholders/admin-edit.png' });
  report.push('admin crop previews, clear, upload and transparent background');
  await page.goto(server.url + '/client/about/');
  await expect(page.locator('img[data-image-preview]')).toHaveCount(10);
  await page.locator('[data-gallery-open="0"]').click();
  await page.locator('[data-gallery-step="1"]').click();
  const expected = await page.locator('[data-gallery-open="1"] img').getAttribute('data-image-preview');
  await expect(page.locator('.gallery-large')).toHaveAttribute('data-image-preview', expected);
  report.push('static about previews and gallery replacement');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await page.locator('.gallery-large').evaluate(el => getComputedStyle(el).transitionDuration)).toBe('0s');
  report.push('reduced motion');
  const withoutJS = await browser.newPage({ javaScriptEnabled: false });
  await withoutJS.route('**/assets/*.webp', route => route.abort());
  await withoutJS.goto(server.url + '/client/about/');
  expect(await withoutJS.locator('img[data-image-preview]').first().evaluate(el => getComputedStyle(el).backgroundImage)).toContain('data:image/webp;base64,');
  await withoutJS.close();
  report.push('static previews exist before JavaScript starts');
  expect(errors).toEqual([]);
  await writeFile('output/image-placeholders/browser-report.json', JSON.stringify({ passed: report, errors }, null, 2));
  console.log('PASS: ' + report.join('; '));
} finally { await browser.close(); await server.stop(); }
